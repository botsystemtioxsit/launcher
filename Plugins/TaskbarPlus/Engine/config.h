#pragma once
#include "common.h"
#include <string>
#include <vector>

// Правило «какой элемент панели что значит»: тип и имя с «*» (пусто — любой). Встроенные правила лежат в движке;
// правила из настроек только ДОБАВЛЯЮТСЯ к ним (файл с правилами не может случайно убрать нужное).
struct Rule
{
    int kind = 0;        // 1 фон, 2 обводка, 3 значок приложения, 4 виджеты, 5 системная область, 8 кадр панели (корень панели задач)
    std::string type, name;
};

// Настройки, которые плагин (C#) кладёт в taskbar-plus-engine.cfg простыми строками «ключ=значение».
// Движок 7 делает одно: пока enabled, родной фон панели прозрачный (плашки и острова рисует сам плагин в своём окне под панелью).
struct Config
{
    bool enabled = false;     // false — панель как в Windows
    bool hideStroke = true;   // убрать тонкую светлую линию по краю панели
    int dump = 0;             // счётчик: изменился — записать дерево элементов панели в файл
    std::vector<Rule> rules;  // дополнительные правила
    std::string rulesSig;     // подпись правил
};

std::wstring ConfigPath();
bool LoadConfig(Config& out, FILETIME& mtime);   // false — файла нет или он не читается
